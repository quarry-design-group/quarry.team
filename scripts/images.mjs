#!/usr/bin/env node
/**
 * Image budget tool for content/asset rasters. One tool, two modes:
 *
 *   node scripts/images.mjs check           — exit 1 if any tracked image busts budget (CI gate)
 *   node scripts/images.mjs fix             — downscale + recompress every over-budget image in place
 *   node scripts/images.mjs fix <files...>  — same, but only the given files (lint-staged pre-commit)
 *
 * Why budgets: sources live in git (ADR-0004) and Astro's pipeline generates the
 * optimized, display-sized derivatives at build — so the site never serves these
 * originals; their only cost is repo/clone weight. The pipeline only ever
 * DOWNSCALES, and the largest display slot is the case-study hero at 1240px
 * (2x DPR = 2480), so a 2560px source cap is invisible on screen. Enforced as a
 * required check + a pre-commit auto-fix so the debt can't re-accrue.
 *
 * Motion assets: motion ships as animated WebP, and animated GIF is NOT
 * permitted. The same clip as GIF costs materially more bytes at lower fidelity
 * (256-colour palette, 1-bit transparency), and the poster contract below is
 * defined on `.webp`. The check hard-fails on any `.gif` in scope and points at
 * the authoring guide; animated WebP is governed by the same byte cap as any
 * raster.
 *
 * Motion is reader-started (WCAG 2.2.2 Pause, Stop, Hide): an animated WebP is
 * authored through the <Motion> component (apps/web/src/components/Motion.astro),
 * which shows a still until the reader asks for the animation. The still is the
 * clip's first frame, written beside it as `<name>.poster.webp` by `fix`, and
 * `check` enforces the pairing — every animated WebP has a poster of the same
 * dimensions, every poster has its clip, and neither is reached from MDX except
 * through <Motion> (a markdown image, a frontmatter field, or a plain <Image>
 * all autoplay it).
 *
 * Provenance: a raster that carries EXIF or XMP fails `check`. Exports from
 * design and photo tools embed author names, account ids and template titles
 * there, and a within-budget file is never re-encoded for bytes alone, so `fix`
 * rewrites any file that carries either block. ICC colour profiles are allowed.
 *
 * Roster avatars are black-and-white (docs/guides/content-authoring.md, Team):
 * a raster under the avatars folder fails `check` when any visible pixel's
 * channels differ by more than AVATAR_TOLERANCE (max(R,G,B) − min(R,G,B)), and
 * `fix` desaturates it. The tolerance absorbs JPEG chroma noise only; a
 * desaturated export measures 0.
 *
 * What `check` cannot see is currency: re-encode a clip at the same dimensions
 * and its old poster still passes. `fix` rewrites the poster whenever the clip's
 * first frame changes, and stages it when the pre-commit hook hands it a clip —
 * lint-staged re-adds only the paths it passed, so an unstaged poster would
 * otherwise let the commit carry a stale still.
 */
import sharp from 'sharp';
import { execSync } from 'node:child_process';
import { existsSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, posix } from 'node:path';

const MAX_EDGE = 2560; // px, long edge
const MAX_BYTES = 900 * 1024; // per file
const SCOPE = ['apps/web/src/content', 'apps/web/src/assets'];
const RASTER = /\.(png|jpe?g|webp)$/i;
const FORBIDDEN = /\.gif$/i; // animated GIF — banned; use animated WebP instead
const POSTER = /\.poster\.webp$/i; // the still of an animated WebP, generated by `fix`
const MOTION_GUIDE = 'docs/guides/content-authoring.md (Motion)';
const MOTION_TAG = /<Motion\b[\s\S]*?\/>/g; // the one sanctioned way to reach a clip
const WEBP_REF = /(?:\.{1,2}\/)?[\w@.-]+\.webp/g; // any relative spelling of a .webp path
const IMPORT_FROM = /^\s*import\s+(\w+)\s+from\s+['"]([^'"]+)['"]/;
const AVATARS = /(?:^|\/)apps\/web\/src\/content\/team\/avatars\//; // black-and-white only
const AVATAR_TOLERANCE = 2; // max per-pixel channel spread; absorbs JPEG chroma noise

/** Justified exceptions: path → reason. Keep this tiny and always explained. */
const ALLOWLIST = new Map([
  // ['apps/web/src/content/cases/foo/hero.jpg', 'full-bleed photographic hero; detail needs the bytes'],
]);

const kb = (n) => `${Math.round(n / 1024)}KB`;

const listed = () =>
  execSync(`git ls-files ${SCOPE.join(' ')}`, { encoding: 'utf8' })
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);

const tracked = () => listed().filter((f) => RASTER.test(f));
const forbidden = () => listed().filter((f) => FORBIDDEN.test(f));
const mdxFiles = () => listed().filter((f) => /\.mdx$/i.test(f));

// lint-staged hands `fix` absolute, platform-separated paths; match on `/`.
const isAvatar = (file) => AVATARS.test(file.replace(/\\/g, '/'));

/** The largest max(R,G,B) − min(R,G,B) over the visible pixels: 0 for a fully
 *  desaturated image. Fully transparent pixels are skipped (their colour never
 *  shows); a one-channel greyscale source decodes to equal R, G and B. */
async function channelSpread(input) {
  const { data } = await sharp(input)
    .toColourspace('srgb')
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let spread = 0;
  for (let i = 0; i < data.length; i += 4) {
    if (data[i + 3] === 0) continue;
    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];
    spread = Math.max(spread, Math.max(r, g, b) - Math.min(r, g, b));
  }
  return spread;
}

const posterOf = (file) => file.replace(/\.webp$/i, '.poster.webp');
const clipOf = (poster) => poster.replace(/\.poster\.webp$/i, '.webp');

/** Stage a file the tool just generated, so it travels with the commit. */
const stage = (file) => {
  try {
    execSync(`git add -- "${file}"`);
  } catch {
    console.warn(`  (could not stage ${file} — add it before committing)`);
  }
};

async function inspect(file) {
  const bytes = statSync(file).size;
  const meta = await sharp(file).metadata();
  const edge = Math.max(meta.width || 0, meta.height || 0);
  const reasons = [];
  if (edge > MAX_EDGE) reasons.push(`${edge}px > ${MAX_EDGE}px`);
  if (bytes > MAX_BYTES) reasons.push(`${kb(bytes)} > ${kb(MAX_BYTES)}`);
  if (meta.exif || meta.xmp) reasons.push('embedded EXIF/XMP metadata');
  if (isAvatar(file)) {
    const spread = await channelSpread(file);
    if (spread > AVATAR_TOLERANCE)
      reasons.push(
        `color avatar: channel spread ${spread} > ${AVATAR_TOLERANCE} (must be black-and-white)`,
      );
  }
  return {
    file,
    bytes,
    edge,
    format: meta.format,
    width: meta.width,
    height: meta.height,
    animated: (meta.pages || 1) > 1,
    reasons,
  };
}

/** Downscale to the edge cap and re-encode at high effort, keeping the format
 *  (transcoding would break MDX `./x.png` references). Encodes at a high-quality
 *  default, then — only if still over the byte budget — steps quality/palette
 *  down through a floor to meet it (photos tolerate q74; UI PNGs tolerate a
 *  128-colour palette). A roster avatar with colour in it is desaturated.
 *  Idempotent: only writes when it saves >2%, the source carries EXIF/XMP, or
 *  an avatar needed desaturating, so repeated runs don't generationally degrade. */
async function optimize(file) {
  const before = statSync(file).size;
  const buf = readFileSync(file);
  const meta = await sharp(buf).metadata();
  // Read every frame of animated sources (e.g. animated WebP) so resize/encode
  // preserve the animation instead of collapsing to the first frame.
  const animated = (meta.pages || 1) > 1;
  const desaturate = isAvatar(file) && (await channelSpread(buf)) > AVATAR_TOLERANCE;
  const base = () => {
    const p = sharp(buf, { failOn: 'none', animated })
      .rotate() // bake EXIF orientation, then strip all metadata (sharp default)
      .resize(MAX_EDGE, MAX_EDGE, { fit: 'inside', withoutEnlargement: true });
    return desaturate ? p.grayscale() : p;
  };

  // (encoder settings), best quality first; stop at the first that meets budget.
  const ladder =
    meta.format === 'png'
      ? // No dithering: these sources are re-encoded to webp/avif by Astro's
        // pipeline, and dither noise inflates those derivatives (and the served
        // payload). Flat UI screenshots quantize cleanly without it.
        [{ colours: 256 }, { colours: 128 }, { colours: 64 }].map(
          (o) => (p) =>
            p.png({
              compressionLevel: 9,
              effort: 10,
              palette: true,
              colours: o.colours,
              dither: 0,
            }),
        )
      : meta.format === 'webp'
        ? [82, 78, 72].map((q) => (p) => p.webp({ quality: q, effort: 6 }))
        : [82, 78, 74].map((q) => (p) => p.jpeg({ quality: q, mozjpeg: true }));

  let out;
  for (const encode of ladder) {
    out = await encode(base()).toBuffer();
    if (out.length <= MAX_BYTES) break; // met budget — don't degrade further
  }

  if (out.length < before * 0.98 || meta.exif || meta.xmp || desaturate) {
    writeFileSync(file, out);
    return { file, before, after: out.length, changed: true };
  }
  return { file, before, after: before, changed: false };
}

/** Write the still for an animated WebP: its first frame, same dimensions,
 *  beside it as `<name>.poster.webp`. Deterministic, so a re-run rewrites only
 *  when the clip changed. */
async function writePoster(clip) {
  const poster = posterOf(clip);
  // sharp reads page 0 of a multi-page input unless told otherwise.
  const out = await sharp(readFileSync(clip)).webp({ quality: 82, effort: 6 }).toBuffer();
  const same = existsSync(poster) && readFileSync(poster).equals(out);
  if (!same) writeFileSync(poster, out);
  return { clip, poster, changed: !same };
}

/** Motion contract violations across the tracked tree (see header). */
async function motionViolations(results) {
  const files = new Set(results.map((r) => r.file));
  const clips = results.filter((r) => r.animated && !POSTER.test(r.file));
  const posters = results.filter((r) => POSTER.test(r.file));
  const byFile = new Map(results.map((r) => [r.file, r]));
  const problems = [];

  for (const clip of clips) {
    const poster = byFile.get(posterOf(clip.file));
    if (!poster) {
      problems.push(`${clip.file} — animated, but no ${basename(posterOf(clip.file))} beside it`);
    } else if (poster.animated || poster.width !== clip.width || poster.height !== clip.height) {
      problems.push(`${poster.file} — not a still of ${basename(clip.file)} at its size`);
    }
  }
  for (const poster of posters) {
    const clip = byFile.get(clipOf(poster.file));
    if (!clip)
      problems.push(`${poster.file} — orphan: no animated ${basename(clipOf(poster.file))}`);
    else if (!clip.animated)
      problems.push(`${poster.file} — orphan: ${basename(clip.file)} is not animated`);
  }

  // A clip or poster may only enter an MDX file through <Motion>. Blank the
  // <Motion> tags out (keeping line numbers) and anything left that reaches one
  // — a markdown image, a frontmatter field, an <Image>, an <img> built from an
  // import — would autoplay it. Both spellings are caught: the path, however it
  // is written and whichever entry's folder it points into, and the binding an
  // import introduced.
  const motion = new Set([...clips, ...posters].map((r) => r.file));
  for (const mdx of mdxFiles()) {
    const dir = dirname(mdx);
    const source = readFileSync(mdx, 'utf8').replace(MOTION_TAG, (tag) =>
      tag.replace(/[^\n]/g, ' '),
    );
    const bound = new Map(); // local name → the motion asset it was imported from
    source.split('\n').forEach((line, i) => {
      const where = `${mdx}:${i + 1}`;
      const imported = line.match(IMPORT_FROM);
      if (imported) {
        const target = posix.normalize(posix.join(dir, imported[2]));
        if (motion.has(target)) bound.set(imported[1], basename(target));
        return;
      }
      for (const ref of line.match(WEBP_REF) ?? []) {
        const target = posix.normalize(posix.join(dir, ref));
        if (motion.has(target))
          problems.push(`${where} — ${basename(target)} reached by path; author it with <Motion>`);
      }
      for (const [name, asset] of bound) {
        if (new RegExp(`\\b${name}\\b`).test(line))
          problems.push(`${where} — ${asset} used as \`${name}\` outside <Motion>`);
      }
    });
  }
  return { problems, clips: clips.length, tracked: files.size };
}

const mode = process.argv[2];
const args = process.argv.slice(3);

if (mode === 'check') {
  const banned = forbidden();
  if (banned.length) {
    console.error(
      `\n✘ ${banned.length} animated GIF(s) in content — not permitted; convert to animated WebP:`,
    );
    for (const f of banned) console.error(`  ${f}`);
    console.error(
      `\nWhy: the same clip as GIF costs materially more bytes at lower fidelity (256-colour palette),` +
        `\nand the motion contract (poster + <Motion>) is defined on .webp.` +
        `\nSee docs/guides/content-authoring.md (Images) for the WebP workflow.`,
    );
    process.exit(1);
  }
  const files = tracked();
  const results = await Promise.all(files.map(inspect));
  const bad = results.filter((r) => r.reasons.length && !ALLOWLIST.has(r.file));
  const total = results.reduce((s, r) => s + r.bytes, 0);
  console.log(
    `image budgets: ${files.length} tracked rasters, ${(total / 1048576).toFixed(1)}MB total ` +
      `(cap ${MAX_EDGE}px / ${kb(MAX_BYTES)} per file)`,
  );
  if (bad.length) {
    console.error(
      `\n✘ ${bad.length} image(s) over budget, carrying EXIF/XMP, or a color roster avatar:`,
    );
    for (const r of bad) console.error(`  ${r.file} — ${r.reasons.join(', ')}`);
    console.error(
      `\nFix with:  pnpm images:fix\n(then re-commit; add a justified path to ALLOWLIST only if the bytes are genuinely needed)`,
    );
    process.exit(1);
  }
  const motion = await motionViolations(results);
  console.log(`motion: ${motion.clips} animated WebP clip(s), each reader-started via <Motion>`);
  if (motion.problems.length) {
    console.error(`\n✘ ${motion.problems.length} motion contract violation(s):`);
    for (const p of motion.problems) console.error(`  ${p}`);
    console.error(
      `\nPosters: run  pnpm images:fix  and commit the <name>.poster.webp it writes.` +
        `\nAuthoring: see ${MOTION_GUIDE}.`,
    );
    process.exit(1);
  }
  console.log('✓ all within budget');
} else if (mode === 'fix') {
  // Posters are derived: never re-encoded in place, always regenerated from the clip.
  const files = (args.length ? args : tracked()).filter((f) => RASTER.test(f) && !POSTER.test(f));
  let saved = 0;
  let changed = 0;
  let posters = 0;
  for (const f of files) {
    const r = await optimize(f);
    if (r.changed) {
      changed++;
      saved += r.before - r.after;
      console.log(`  ${f}: ${kb(r.before)} → ${kb(r.after)}`);
    }
    if (/\.webp$/i.test(f) && ((await sharp(f).metadata()).pages || 1) > 1) {
      const p = await writePoster(f);
      if (p.changed) {
        posters++;
        console.log(`  ${p.poster}: written (first frame of ${basename(f)})`);
        // Pre-commit: lint-staged re-adds only the paths it passed, so an
        // unstaged poster would let the commit ship a stale still past `check`
        // (which compares geometry, not content).
        if (args.length) stage(p.poster);
      }
    }
  }
  console.log(
    `\nimages:fix — ${changed}/${files.length} rewritten, ${(saved / 1048576).toFixed(1)}MB saved, ${posters} poster(s) written`,
  );
} else {
  console.error('usage: node scripts/images.mjs check | fix [files...]');
  process.exit(2);
}
